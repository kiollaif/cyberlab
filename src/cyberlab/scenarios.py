"""Первый сценарий. Все адреса вымышлены, последствия существуют только в модели."""

from cyberlab.domain import Choice, Scenario, ScenarioNode, StateChange

PHISHING = Scenario(
    id="phishing-v1",
    title="Письмо от «службы поддержки»",
    start_node="inbox",
    nodes=(
        ScenarioNode(
            "inbox",
            "До блокировки аккаунта — 15 минут",
            "Вы начинаете рабочий день. Во входящих — срочное письмо: пароль якобы истекает, "
            "а доступ к проекту скоро заблокируют. Отправитель предлагает подтвердить учётную "
            "запись по ссылке.\n\nКак вы поступите?",
            (
                Choice(
                    "inspect",
                    "Проверить письмо",
                    "Посмотреть адрес отправителя и цель ссылки",
                    "inspected",
                    "Проверены адрес отправителя и адрес ссылки.",
                    StateChange(email_inspected=True),
                ),
                Choice(
                    "open_link",
                    "Открыть ссылку",
                    "Перейти на страницу из учебного письма",
                    "fake_site",
                    "Открыта поддельная страница входа внутри симуляции.",
                    StateChange(risk=30, browser_open=True),
                ),
                Choice(
                    "report",
                    "Сообщить о подозрительном письме",
                    "Передать письмо службе безопасности",
                    "reported",
                    "Письмо передано службе безопасности и помещено в карантин.",
                    StateChange(risk=0, email_quarantined=True),
                ),
            ),
        ),
        ScenarioNode(
            "inspected",
            "Знакомое имя, чужой адрес",
            "Видимое имя — «IT-поддержка», но отправитель — help@cyberlab-support.invalid. "
            "Ссылка ведёт на login.cyberlab-check.invalid. Оба адреса отличаются от учебного "
            "корпоративного домена cyberlab.example.\n\n"
            "Срочность и похожий домен — признаки фишинга. "
            "Проверьте обращение через известный канал связи.",
            (
                Choice(
                    "report",
                    "Сообщить о фишинге",
                    "Изолировать письмо и предупредить специалистов",
                    "reported",
                    "После проверки письмо отправлено в карантин; атака остановлена.",
                    StateChange(risk=0, email_quarantined=True),
                ),
                Choice(
                    "open_link",
                    "Всё же открыть ссылку",
                    "Проверить, что произойдёт дальше",
                    "fake_site",
                    "Несмотря на признаки фишинга открыта поддельная страница.",
                    StateChange(risk=30, browser_open=True),
                ),
            ),
        ),
        ScenarioNode(
            "fake_site",
            "Страница просит ваш пароль",
            "Страница похожа на корпоративный вход. В адресе — чужой домен. "
            "Форма предлагает срочно подтвердить пароль.\n\nНастоящие данные вводить не нужно: "
            "кнопка ниже моделирует отправку вымышленного пароля.",
            (
                Choice(
                    "submit",
                    "Отправить учебный пароль",
                    "Смоделировать передачу учётных данных",
                    "compromised",
                    "Учебный пароль передан злоумышленнику; аккаунт скомпрометирован.",
                    StateChange(risk=75, credentials_exposed=True),
                ),
                Choice(
                    "close_report",
                    "Закрыть страницу и сообщить",
                    "Остановиться до передачи данных",
                    "contained",
                    "Страница закрыта, письмо помещено в карантин; пароль не раскрыт.",
                    StateChange(risk=10, browser_open=False, email_quarantined=True),
                ),
            ),
        ),
        ScenarioNode(
            "compromised",
            "Обнаружен посторонний вход",
            "После отправки пароля появился новый сеанс входа. На виртуальном компьютере "
            "замечена подозрительная активность.\n\nМожно ограничить ущерб: отключить сеть "
            "и уведомить специалистов. Это не отменяет раскрытия пароля.",
            (
                Choice(
                    "isolate",
                    "Изолировать компьютер и сообщить",
                    "Отключить учебную сеть и остановить атаку",
                    "isolated",
                    "Сеть отключена, специалисты уведомлены; дальнейшая атака остановлена.",
                    StateChange(
                        risk=40, network_connected=False, browser_open=False, email_quarantined=True
                    ),
                ),
                Choice(
                    "ignore",
                    "Продолжить работу",
                    "Оставить подозрительную активность без ответа",
                    "damage",
                    "Атака продолжилась: виртуальные файлы отмечены как зашифрованные.",
                    StateChange(risk=100, files_encrypted=True),
                ),
            ),
        ),
        ScenarioNode(
            "reported",
            "Атака остановлена до утечки",
            "Письмо в карантине. Учётные данные и файлы защищены. "
            "Проверка отправителя и сообщение о подозрении помогли остановить атаку.\n\n"
            "Вернитесь к любому шагу слева и попробуйте другое решение. Первая ветка сохранится.",
        ),
        ScenarioNode(
            "contained",
            "Вы остановились вовремя",
            "Поддельная страница закрыта, пароль не отправлен, письмо в карантине. "
            "Переход по подозрительной ссылке создал риск, "
            "но раскрытия данных удалось избежать.\n\n"
            "Вернитесь к странице входа и сравните этот результат с отправкой пароля.",
        ),
        ScenarioNode(
            "isolated",
            "Ущерб ограничен, пароль раскрыт",
            "Отключение сети сохранило виртуальные файлы. Однако пароль уже раскрыт. "
            "В реальной ситуации специалистам нужно отозвать сеансы и сменить пароль "
            "через доверенный канал.\n\nСравните эту ветку с ранним сообщением о фишинге.",
        ),
        ScenarioNode(
            "damage",
            "Атака затронула файлы",
            "В модели пароль раскрыт, а файлы стали недоступны. Игнорирование признаков "
            "компрометации увеличило ущерб. Настоящие файлы компьютера не затрагивались.\n\n"
            "Выберите более ранний шаг слева и создайте альтернативную ветку.",
        ),
    ),
)
