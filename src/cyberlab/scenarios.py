"""Первый сценарий. Все адреса вымышлены, последствия существуют только в модели."""

from cyberlab.domain import Choice, Scenario, ScenarioNode, StateChange

PHISHING = Scenario(
    id="phishing-v1",
    title="Письмо от «службы поддержки»",
    start_node="inbox",
    nodes=(
        ScenarioNode(
            id="inbox",
            title="До блокировки аккаунта — 15 минут",
            description="Вы начинаете рабочий день. "
            "Во входящих — срочное письмо: пароль якобы истекает, "
            "а доступ к проекту скоро заблокируют. Отправитель предлагает подтвердить учётную "
            "запись по ссылке.\n\nКак вы поступите?",
            choices=(
                Choice(
                    id="inspect",
                    title="Проверить письмо",
                    hint="Посмотреть адрес отправителя и цель ссылки",
                    next_node="inspected",
                    event="Проверены адрес отправителя и адрес ссылки.",
                    change=StateChange(email_inspected=True),
                ),
                Choice(
                    id="open_link",
                    title="Открыть ссылку",
                    hint="Перейти на страницу из учебного письма",
                    next_node="fake_site",
                    event="Открыта поддельная страница входа внутри симуляции.",
                    change=StateChange(risk=30, browser_open=True),
                ),
                Choice(
                    id="report",
                    title="Сообщить о подозрительном письме",
                    hint="Передать письмо службе безопасности",
                    next_node="reported",
                    event="Письмо передано службе безопасности и помещено в карантин.",
                    change=StateChange(risk=0, email_quarantined=True),
                ),
            ),
        ),
        ScenarioNode(
            id="inspected",
            title="Знакомое имя, чужой адрес",
            description="Видимое имя — «IT-поддержка», "
            "но отправитель — help@cyberlab-support.invalid. "
            "Ссылка ведёт на login.cyberlab-check.invalid. Оба адреса отличаются от учебного "
            "корпоративного домена cyberlab.example.\n\n"
            "Срочность и похожий домен — признаки фишинга. "
            "Проверьте обращение через известный канал связи.",
            choices=(
                Choice(
                    id="report",
                    title="Сообщить о фишинге",
                    hint="Изолировать письмо и предупредить специалистов",
                    next_node="reported",
                    event="После проверки письмо отправлено в карантин; атака остановлена.",
                    change=StateChange(risk=0, email_quarantined=True),
                ),
                Choice(
                    id="open_link",
                    title="Всё же открыть ссылку",
                    hint="Проверить, что произойдёт дальше",
                    next_node="fake_site",
                    event="Несмотря на признаки фишинга открыта поддельная страница.",
                    change=StateChange(risk=30, browser_open=True),
                ),
            ),
        ),
        ScenarioNode(
            id="fake_site",
            title="Страница просит ваш пароль",
            description="Страница похожа на корпоративный вход. В адресе — чужой домен. "
            "Форма предлагает срочно подтвердить пароль.\n\nНастоящие данные вводить не нужно: "
            "кнопка ниже моделирует отправку вымышленного пароля.",
            choices=(
                Choice(
                    id="submit",
                    title="Отправить учебный пароль",
                    hint="Смоделировать передачу учётных данных",
                    next_node="compromised",
                    event="Учебный пароль передан злоумышленнику; аккаунт скомпрометирован.",
                    change=StateChange(risk=75, credentials_exposed=True),
                ),
                Choice(
                    id="close_report",
                    title="Закрыть страницу и сообщить",
                    hint="Остановиться до передачи данных",
                    next_node="contained",
                    event="Страница закрыта, письмо помещено в карантин; пароль не раскрыт.",
                    change=StateChange(risk=10, browser_open=False, email_quarantined=True),
                ),
            ),
        ),
        ScenarioNode(
            id="compromised",
            title="Обнаружен посторонний вход",
            description="После отправки пароля появился новый сеанс входа. "
            "На виртуальном компьютере "
            "замечена подозрительная активность.\n\nМожно ограничить ущерб: отключить сеть "
            "и уведомить специалистов. Это не отменяет раскрытия пароля.",
            choices=(
                Choice(
                    id="isolate",
                    title="Изолировать компьютер и сообщить",
                    hint="Отключить учебную сеть и остановить атаку",
                    next_node="isolated",
                    event="Сеть отключена, специалисты уведомлены; дальнейшая атака остановлена.",
                    change=StateChange(
                        risk=40, network_connected=False, browser_open=False, email_quarantined=True
                    ),
                ),
                Choice(
                    id="ignore",
                    title="Продолжить работу",
                    hint="Оставить подозрительную активность без ответа",
                    next_node="damage",
                    event="Атака продолжилась: виртуальные файлы отмечены как зашифрованные.",
                    change=StateChange(risk=100, files_encrypted=True),
                ),
            ),
        ),
        ScenarioNode(
            id="reported",
            title="Атака остановлена до утечки",
            description="Письмо в карантине. Учётные данные и файлы защищены. "
            "Проверка отправителя и сообщение о подозрении помогли остановить атаку.\n\n"
            "Вернитесь к любому шагу слева и попробуйте другое решение. Первая ветка сохранится.",
        ),
        ScenarioNode(
            id="contained",
            title="Вы остановились вовремя",
            description="Поддельная страница закрыта, пароль не отправлен, письмо в карантине. "
            "Переход по подозрительной ссылке создал риск, "
            "но раскрытия данных удалось избежать.\n\n"
            "Вернитесь к странице входа и сравните этот результат с отправкой пароля.",
        ),
        ScenarioNode(
            id="isolated",
            title="Ущерб ограничен, пароль раскрыт",
            description="Отключение сети сохранило виртуальные файлы. Однако пароль уже раскрыт. "
            "В реальной ситуации специалистам нужно отозвать сеансы и сменить пароль "
            "через доверенный канал.\n\nСравните эту ветку с ранним сообщением о фишинге.",
        ),
        ScenarioNode(
            id="damage",
            title="Атака затронула файлы",
            description="В модели пароль раскрыт, а файлы стали недоступны. "
            "Игнорирование признаков "
            "компрометации увеличило ущерб. Настоящие файлы компьютера не затрагивались.\n\n"
            "Выберите более ранний шаг слева и создайте альтернативную ветку.",
        ),
    ),
)
