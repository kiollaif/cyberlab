def explain_term(question: str) -> str | None:
    normalized = question.casefold()
    # HTTPS проверяем раньше общего слова «адрес», чтобы вопрос о замке в браузере
    # не получил определение домена вместо объяснения шифрования.
    if "https" in normalized:
        return TERMS["HTTPS"]
    for keyword, term in KEYWORDS.items():
        if keyword in normalized:
            return TERMS[term]
    return None
